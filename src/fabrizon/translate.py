"""Stage 4: turn a resolved mixin handler into a helper file plus a brief.

What this does, precisely:

1. Decompiles the handler's bytecode (``javacode.py``) into readable statements.
2. Translates the statements that are mechanically safe to Rust and comments out
   the rest, so the helper always compiles as a private, synchronous, safe `fn`
   with no attributes and no generics - the contract horizon-mixins requires.
3. Derives the typed `bindings` the helper needs from the *target's own*
   signature, which is the only place the Rust types are known.
4. Writes a brief (`BRIEF.md`) with everything a human or an AI needs to finish
   the body: the Java listing, the target signature, the bindings, and why each
   remaining statement was not translated.

It never invents a Horizon API path. A call into Minecraft is a comment, not a
guess: `horizon-mixins check` is the only proof that a helper is correct.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

from .analysis import Finding, Report
from .classfile import ClassInfo, Member
from .javacode import decompile, type_name
from .resolve import Candidate, Resolution, snake

AI_NOTE = ("// Generated by Fabrizon (https://ko-fi.com/melthedev). Unofficial. "
           "Part of this body is recovered from bytecode; anything marked TODO needs Horizon's API.\n")

_CALLBACK = ("org/spongepowered/asm/mixin/injection/callback/", "com/llamalad7/mixinextras/")
_SKIP_PARAM = ("CallbackInfo", "CallbackInfoReturnable", "LocalCapture", "LocalRef", "Operation",
               "Expression", "UnaryOperator", "BinaryOperator")


@dataclass
class Binding:
    name: str
    ty: str
    value: str

    def toml(self) -> str:
        return f'{{ name = "{self.name}", ty = "{_toml(self.ty)}", value = "{_toml(self.value)}" }}'


@dataclass
class Helper:
    filename: str
    fn_name: str
    source: str
    bindings: list[Binding] = field(default_factory=list)
    complete: bool = False
    notes: list[str] = field(default_factory=list)
    java: list[str] = field(default_factory=list)
    translation: list[str] = field(default_factory=list)
    target: Candidate | None = None
    kind: str = ""
    cancellable: bool = False


def _toml(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def _ident(s: str) -> str:
    s = re.sub(r"[^A-Za-z0-9_]+", "_", s)
    s = re.sub(r"_+", "_", s).strip("_")
    if not s or s[0].isdigit():
        s = "h_" + s
    return s.lower()


def _params(desc: str) -> list[str]:
    from .javacode import _split_desc

    return _split_desc(desc)


def _skip_param(desc: str) -> bool:
    if any(desc.startswith("L" + p) or desc.startswith("L" + p) for p in _CALLBACK):
        return True
    name = desc.rsplit("/", 1)[-1].rstrip(";")
    return any(name.startswith(s) for s in _SKIP_PARAM)


def _is_callback(desc: str) -> bool:
    return any(desc.startswith("L" + p) for p in _CALLBACK)


def _code_lines(translation_lines: list[str]) -> tuple[list[str], bool]:
    """Comment out every line that is not valid Rust on its own; return (lines, all_code).

    Commenting is block-aware: when a line that opens a brace has to be commented
    (an `if` whose condition needs Horizon's API), its body and its closing brace are
    commented with it, so the emitted helper still parses as Rust.
    """
    out: list[str] = []
    all_code = True
    depth = 0
    for line in translation_lines:
        stripped = line.strip()
        if not stripped:
            out.append(line)
            continue
        already_comment = stripped.startswith("//")
        bad = not already_comment and ("/*" in stripped or "*/" in stripped)
        if depth or bad:
            all_code = False
            if already_comment:
                out.append(line)
            else:
                out.append(re.sub(r"^(\s*)", r"\1// ", line))
                depth += stripped.count("{") - stripped.count("}")
                if depth < 0:
                    depth = 0
        else:
            out.append(line)
    return out, all_code


def _find_handler(jar, resolution: Resolution) -> tuple[ClassInfo | None, Member | None]:
    if jar is None:
        return None, None
    for mc in jar.mixin_classes:
        if mc.info.name == resolution.mixin:
            for m in mc.info.methods:
                if m.name == resolution.member:
                    return mc.info, m
    return None, None


def _bind_value_param(target: Candidate, handler: Member, renames: dict[int, str]) -> Binding | None:
    """For RETURN / ModifyReturnValue: bind the original result as `$value`."""
    if not target.ret:
        return None
    renames[0] = "value"
    return Binding("value", target.ret, "$value")


def build_helper(resolution: Resolution, jar, crate: str) -> Helper | None:
    """Build one helper for a resolved finding, or None when there is nothing to emit."""
    cand = resolution.candidates[0] if resolution.candidates else None
    if cand is None:
        return None
    ci, handler = _find_handler(jar, resolution)
    kind = resolution.kind or ""
    cancellable = "cancellable = true" in (resolution.notes or []) or False
    fn_name = _ident(f"{resolution.member}_{resolution.readable_method or resolution.java_method}")
    helper = Helper(
        filename=fn_name + ".rs",
        fn_name=fn_name,
        source="",
        target=cand,
        kind=kind,
        cancellable=cancellable,
    )

    renames: dict[int, str] = {}
    bindings: list[Binding] = []
    if kind == "RETURN" and cand.ret:
        b = _bind_value_param(cand, handler, renames)
        if b:
            bindings.append(b)

    translation = None
    if handler is not None and handler.code is not None:
        translation = decompile(handler.code, ci.name, handler.descriptor, renames)

    body: list[str] = []
    if translation is not None:
        helper.java = translation.java_lines
        helper.notes = list(translation.notes)
        helper.translation = translation.lines
        body, all_code = _code_lines(translation.lines)
        helper.complete = translation.complete and all_code
    else:
        helper.notes = ["handler body not available (no Code attribute)"]
        helper.complete = False

    # Bindings are only valid when the helper actually takes them, in declaration order.
    used = set(translation.used) if translation else set()
    bindings = [b for b in bindings if b.name in used] or ([bindings[0]] if kind == "RETURN" and bindings else [])
    helper.bindings = bindings

    args = ", ".join(f"{b.name}: {b.ty}" for b in bindings)
    ret = ""
    if kind == "HEAD" and cancellable:
        ret = " -> std::ops::ControlFlow<()>"
    elif kind == "RETURN" and cand.ret:
        ret = f" -> {cand.ret}"

    header = (
        f"{AI_NOTE}"
        f"// From Fabric mixin {resolution.mixin}#{resolution.member} ({resolution.side} side)\n"
        f"// Java target: {resolution.java_target}#{resolution.java_method}\n"
        f"// Horizon target: {cand.crate or crate}::{cand.path} ({cand.file}:{cand.line})\n"
    )
    if helper.notes:
        header += "// Not translated (see BRIEF.md): " + "; ".join(helper.notes) + "\n"

    lines = [header.rstrip("\n"), f"fn {fn_name}({args}){ret} {{"]
    lines += [b.rstrip() for b in body]
    if kind == "HEAD" and cancellable:
        lines.append("    // TODO(stage 4): cancel by returning std::ops::ControlFlow::Break(())")
        lines.append("    std::ops::ControlFlow::Continue(())")
    elif kind == "RETURN" and cand.ret:
        # The translated body may end in `return <expr>;`; make it the tail expression.
        tail = [b for b in body if b.strip()]
        if tail and tail[-1].strip().startswith("return ") and tail[-1].strip().endswith(";"):
            expr = tail[-1].strip()[len("return "):-1]
            if "/*" not in expr:
                lines = [l for l in lines if l is not tail[-1]]
                lines.append("    " + expr)
            else:
                lines.append("    value")
        elif not helper.complete:
            lines.append("    value // unchanged: the original result passes through")
        else:
            lines.append("    value")
    lines.append("}")
    helper.source = "\n".join(lines) + "\n"
    return helper


def render_brief(helpers: list[Helper], crate: str, mod_id: str) -> str:
    out = [f"# Translation brief: {mod_id}", "",
           "Every helper below compiles as a private, synchronous, safe `fn` (the horizon-mixins",
           "contract). Statements Fabrizon could translate are Rust; the rest are comments with the",
           "Java they came from, because they call Minecraft or Horizon APIs whose Rust path cannot",
           "be derived from a jar. Fill those in, then run `horizon-mixins plan` and `check`.", ""]
    if not helpers:
        return "\n".join(out + ["No helper was emitted."]) + "\n"
    for h in helpers:
        t = h.target
        out += [f"## `{h.filename}`", ""]
        out.append(f"- kind: `{h.kind}`" + (" (cancellable)" if h.cancellable else ""))
        if t:
            out.append(f"- target: `{t.crate or crate}::{t.path}` (`{t.file}:{t.line}`)")
            out.append(f"- target signature: `{_sig(t)}`")
        out.append(f"- helper: `fn {h.fn_name}({', '.join(b.name + ': ' + b.ty for b in h.bindings)})`")
        out.append(f"- state: {'translated' if h.complete else 'needs work'}")
        if h.bindings:
            out.append("- bindings: " + ", ".join(f"`{b.name}` = `{b.value}`" for b in h.bindings))
        if h.notes:
            out.append("- not translated: " + "; ".join(f"`{n}`" for n in h.notes))
        if h.java:
            out += ["", "Java handler (recovered):", "```java", *h.java, "```"]
        if h.translation:
            out += ["", "Recovered Rust:", "```rust", *h.translation, "```"]
        out.append("")
    return "\n".join(out) + "\n"


def _sig(c: Candidate) -> str:
    params = ", ".join(f"{p['name']}: {p['ty']}" for p in c.params)
    return f"fn {c.path.rsplit('::', 1)[-1]}({params})" + (f" -> {c.ret}" if c.ret else "")
